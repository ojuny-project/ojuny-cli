#!/usr/bin/env bash
set -euo pipefail

repo_root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
output=${1:-"$repo_root/docs/cli-reference.md"}
workdir=$(mktemp -d)
trap 'rm -rf "$workdir"' EXIT

export LC_ALL=C

cat >"$workdir/capture.sh" <<'CAPTURE'
set -euo pipefail
out=$1
export HOME
HOME=$(mktemp -d)
ojuny --help >"$out/ojuny-help.txt"
ojuny-patches --help >"$out/ojuny-patches-help.txt"
awk '/^Categories:/ { found = 1; next } found && /^[[:space:]]*$/ { exit } found { print $1 }' \
    "$out/ojuny-help.txt" | sort >"$out/categories.txt"
while IFS= read -r category; do
    ojuny help "$category" >"$out/group-$category.txt"
done <"$out/categories.txt"
CAPTURE

nix shell "$repo_root#ojuny-cli" "$repo_root#ojuny-patches-cli" \
    -c bash "$workdir/capture.sh" "$workdir"

section_rows() {
    awk -v section="$1" '
        $0 == section ":" { inside = 1; next }
        inside && /^[[:space:]]*$/ { exit }
        inside {
            line = $0
            sub(/^[[:space:]]+/, "", line)
            if (line == "") next
            if (match(line, /  +/)) {
                name = substr(line, 1, RSTART - 1)
                description = substr(line, RSTART + RLENGTH)
            } else {
                name = line
                description = ""
            }
            gsub(/\|/, "\\|", name)
            gsub(/\|/, "\\|", description)
            printf "| `%s` | %s |\n", name, description
        }
    ' "$2"
}

group_rows() {
    awk -v base="Usage: ojuny $2" -v category="$2" '
        NR == 1 { usage = $0; next }
        /^[[:space:]]+[^[:space:]]/ {
            line = $0
            sub(/^[[:space:]]+/, "", line)
            if (match(line, /  +/)) {
                name = substr(line, 1, RSTART - 1)
                description = substr(line, RSTART + RLENGTH)
            } else {
                name = line
                description = ""
            }
            gsub(/\|/, "\\|", name)
            gsub(/\|/, "\\|", description)
            printf "| `%s` | %s |\n", name, description
            rows += 1
        }
        END {
            if (rows > 0) exit
            if (usage == base) {
                printf "| `%s` | |\n", category
            } else if (index(usage, base " ") == 1) {
                name = substr(usage, length(base) + 2)
                gsub(/\|/, "\\|", name)
                printf "| `%s` | |\n", name
            }
        }
    ' "$1"
}

category_description() {
    awk -v wanted="$1" '
        $0 == "Categories:" { inside = 1; next }
        inside && /^[[:space:]]*$/ { exit }
        inside {
            line = $0
            sub(/^[[:space:]]+/, "", line)
            split(line, parts, /  +/)
            if (parts[1] == wanted) {
                description = line
                sub(/^[^[:space:]]+[[:space:]]+/, "", description)
                print description
                exit
            }
        }
    ' "$2"
}

{
    cat <<'HEADER'
# ojuny CLI reference

Status: generated. The CLI is incomplete and untested; parts of the designed
command surface are not implemented. This page lists only what the binaries
expose in `--help` today.

Generated by `scripts/gen-cli-reference.sh` from the `--help` output of
`ojuny-cli` and `ojuny-patches-cli`. Do not edit it by hand. The docs workflow
regenerates the page and fails when the checked-in copy differs.

Regenerate with:

```sh
./scripts/gen-cli-reference.sh
```

## `ojuny`

```sh
nix shell .#ojuny-cli -c ojuny --help
```

### Options

| Option | Description |
| --- | --- |
HEADER
    section_rows "Options" "$workdir/ojuny-help.txt"
    cat <<'CATEGORIES'

### Categories

| Category | Description |
| --- | --- |
CATEGORIES
    section_rows "Categories" "$workdir/ojuny-help.txt"

    while IFS= read -r category; do
        description=$(category_description "$category" "$workdir/ojuny-help.txt")
        printf '\n### `ojuny %s`\n\n' "$category"
        if [ -n "$description" ]; then
            printf '%s\n\n' "$description"
        fi
        cat <<'TABLE'
| Command | Description |
| --- | --- |
TABLE
        group_rows "$workdir/group-$category.txt" "$category"
    done <"$workdir/categories.txt"

    cat <<'PATCHES'

## `ojuny-patches`

```sh
nix shell .#ojuny-patches-cli -c ojuny-patches --help
```

### Options

| Option | Description |
| --- | --- |
PATCHES
    section_rows "Options" "$workdir/ojuny-patches-help.txt"
    cat <<'COMMANDS'

### Commands

| Command | Description |
| --- | --- |
COMMANDS
    section_rows "Commands" "$workdir/ojuny-patches-help.txt"
} >"$output.tmp"

mv "$output.tmp" "$output"
printf 'wrote %s\n' "$output"
