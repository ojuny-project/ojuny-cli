#!/usr/bin/env bash
set -euo pipefail

repo_root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
output=${1:-"$repo_root/docs/cli-reference.md"}
table="$repo_root/src/ojuny-cli/lib/commands.tsv"

escape() {
    printf '%s' "$1" | sed 's/|/\\|/g'
}

{
    cat <<'HEADER'
# ojuny CLI reference

Status: generated. The core surface is implemented and the optional patch
stacks are out of scope. This page is generated from the command table, not
from `--help` scraping.

Generated by `scripts/gen-cli-reference.sh` from
`src/ojuny-cli/lib/commands.tsv`. Do not edit it by hand. The docs workflow
regenerates the page and fails when the checked-in copy differs.

Regenerate with:

```sh
./scripts/gen-cli-reference.sh
```

## `ojuny`

```sh
nix shell .#ojuny-cli -c ojuny --help
```

### Options

| Option | Description |
| --- | --- |
| `--json` | Emit one JSON document on stdout |
| `--quiet` | Print only the primary value |
| `--verbose` | Print the resolved backend argv to stderr |
| `--no-color` | Disable color |
| `--yes`, `-y` | Do not prompt |
| `--dry-run` | Print the backend argv and do not execute |
| `--system` | Use the system systemctl or journalctl scope |
| `--flake <path>` | Use this flake |
| `--host <name>` | Use this host |
| `-h, --help` | Show help |
| `-V, --version` | Show version |

### Top-level commands

| Command | Description |
| --- | --- |
HEADER

    awk -F '\t' '$1 == "top" { printf "| `%s` | %s |\n", $2, $5 }' "$table"

    cat <<'CATEGORIES'

### Categories

| Category | Description |
| --- | --- |
CATEGORIES

    awk -F '\t' '$1 == "cat" { printf "| `%s` | %s |\n", $2, $5 }' "$table"

    while IFS=$'\t' read -r category summary; do
        printf '\n### `ojuny %s`\n\n%s\n\n' "$category" "$summary"
        printf '| Command | Usage | Description |\n| --- | --- | --- |\n'
        rows="$(awk -F '\t' -v category="$category" '
            $1 == "cmd" && $2 ~ ("^" category "\\.") {
                sub("^" category "\\.", "", $2)
                usage = $4
                if (usage == "-") usage = ""
                printf "| `%s` | `%s` | %s |\n", $2, usage, $5
            }
        ' "$table")"
        if [ -n "$rows" ]; then
            printf '%s\n' "$rows"
        else
            case "$category" in
            dispatch) printf '| `<dispatcher> [arguments]` |  | Raw Mango dispatch |\n' ;;
            run) printf '| `<application> [arguments]` |  | Launch an application |\n' ;;
            logs) printf '| `[unit]` |  | Journal logs |\n' ;;
            esac
        fi
    done < <(awk -F '\t' '$1 == "cat" { printf "%s\t%s\n", $2, $5 }' "$table")

    cat <<'PATCHES'

## `ojuny-patches`

```sh
nix shell .#ojuny-patches-cli -c ojuny-patches --help
```

### Options

| Option | Description |
| --- | --- |
| `--flake <path>` | Use this flake as the local repository |
| `--yes` | Do not prompt |
| `-h, --help` | Show help |
| `-V, --version` | Show version |

### Commands

| Command | Description |
| --- | --- |
| `sync [repo]` | Clone or update repositories |
| `list available\|installed` | List patches |
| `configure <key> <value>` | Set local_repository or patch_directory |
| `repo list\|add\|remove` | Manage repositories |
| `install <id>` | Install a patch and its dependencies |
| `remove <id>` | Remove an installed patch |
| `info <id>` | Show patch information |
| `reinstall <id>` | Remove and install a patch |
PATCHES
} >"$output.tmp"

mv "$output.tmp" "$output"
printf 'wrote %s\n' "$output"
